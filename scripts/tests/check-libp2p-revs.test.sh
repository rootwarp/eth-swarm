#!/usr/bin/env bash
# Tests for scripts/check-libp2p-revs.sh. Run: bash scripts/tests/check-libp2p-revs.test.sh
# Offline: a local git repo stands in for rust-libp2p (master: base -> fix -> later, plus a side
# branch without the fix and a fork branch with it but off master), and fixture workspaces hold a Cargo.toml and a Cargo.lock pinned to its
# commits. The real Cargo.lock is checked with the ancestry step stubbed out (CI runs the real
# script, which fetches rust-libp2p). Works on bash 3.2.
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
script="$here/../check-libp2p-revs.sh"
repo=$(cd "$here/../.." && pwd)
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

# --- the stand-in upstream repo ---
upstream="$tmp/upstream"
g() { git -C "$upstream" -c user.name=t -c user.email=t@example.invalid -c commit.gpgsign=false "$@"; }
git init -q "$upstream"
g symbolic-ref HEAD refs/heads/master
g config uploadpack.allowFilter true
g config uploadpack.allowAnySHA1InWant true
g commit -q --allow-empty -m base
base=$(g rev-parse HEAD)
g commit -q --allow-empty -m "fix(gossipsub): reject key in anonymous mode"
fix=$(g rev-parse HEAD)
g commit -q --allow-empty -m later
later=$(g rev-parse HEAD)
g checkout -q -b side "$base"
g commit -q --allow-empty -m "side branch without the fix"
side=$(g rev-parse HEAD)
g checkout -q -b fork "$later"
g commit -q --allow-empty -m "fork commit on top of the fix, never merged to master"
forked=$(g rev-parse HEAD)
# A copy of the upstream without a master branch.
nomaster="$tmp/nomaster"
git clone -q --bare "$upstream" "$nomaster"
git -C "$nomaster" update-ref -d refs/heads/master
git -C "$nomaster" config uploadpack.allowFilter true
git -C "$nomaster" config uploadpack.allowAnySHA1InWant true
absent=0123456789abcdef0123456789abcdef01234567
remote="LIBP2P_REMOTE=file://$upstream"
fixenv="LIBP2P_FIX_COMMIT=$fix"
url=https://github.com/libp2p/rust-libp2p

# --- fixture workspaces ---
# src <sha>: the Cargo.lock source of a crate patched to <sha>.
src() { printf 'git+%s?rev=%s#%s' "$url" "$1" "$1"; }

# pkg <name> <version> [source]: one Cargo.lock [[package]] entry.
pkg() {
  printf '\n[[package]]\nname = "%s"\nversion = "%s"\n' "$1" "$2"
  if [[ -n ${3:-} ]]; then printf 'source = "%s"\n' "$3"; fi
}

# fixture <name> <sha>: a workspace whose libp2p crates all come from <sha>; prints its root.
fixture() {
  local root="$tmp/$1" sha=$2
  mkdir -p "$root"
  {
    printf '[workspace]\nmembers = ["p2p"]\n\n[patch.crates-io]\n'
    for c in libp2p libp2p-core libp2p-swarm; do printf '%s = { git = "%s", rev = "%s" }\n' "$c" "$url" "$sha"; done
  } > "$root/Cargo.toml"
  {
    printf '# This file is automatically @generated by Cargo.\nversion = 4\n'
    pkg p2p 0.1.0
    pkg libp2p 0.57.1 "$(src "$sha")"
    pkg libp2p-core 0.44.0 "$(src "$sha")"
    pkg libp2p-swarm 0.48.0 "$(src "$sha")"
    pkg multistream-select 0.14.0 "$(src "$sha")"
    pkg tokio 1.53.3 "registry+https://github.com/rust-lang/crates.io-index"
  } > "$root/Cargo.lock"
  echo "$root"
}

passed=0 failed=0

# check <expect: pass|fail> <description> <output substring or ""> <root> [env assignments...]
check() {
  local expect=$1 desc=$2 want=$3 root=$4 rc=0 out ok=0
  shift 4
  out=$(env "$@" bash "$script" "$root" 2>&1) || rc=$?
  if { [[ $expect == pass ]] && ((rc == 0)); } || { [[ $expect == fail ]] && ((rc != 0)); }; then ok=1; fi
  if ((ok)) && [[ -n $want ]] && ! grep -qF -- "$want" <<<"$out"; then ok=0; fi
  if ((ok)); then
    passed=$((passed + 1)); echo "ok   - $desc"
  else
    failed=$((failed + 1)); echo "FAIL - $desc (exit $rc)"; printf '%s\n' "$out" | sed 's/^/       /'
  fi
}

# One SHA that contains the fix.
root=$(fixture later "$later")
check pass "one SHA, a descendant of the fix" "libp2p revs OK" "$root" "$remote" "$fixenv"
root=$(fixture at-fix "$fix")
check pass "one SHA, the fix commit itself" "libp2p revs OK" "$root" "$remote" "$fixenv"

# Ancestry.
root=$(fixture before "$base")
check fail "SHA before the fix" "does not contain" "$root" "$remote" "$fixenv"
root=$(fixture side "$side")
check fail "SHA on a branch without the fix" "does not contain" "$root" "$remote" "$fixenv"
root=$(fixture absent "$absent")
check fail "SHA the remote does not have: fail closed" "cannot fetch" "$root" "$remote" "$fixenv"
root=$(fixture unreachable "$later")
check fail "remote unreachable: fail closed" "cannot fetch" "$root" "LIBP2P_REMOTE=file://$tmp/nowhere" "$fixenv"
root=$(fixture forked "$forked")
check fail "SHA with the fix but not on master (a fork commit served by SHA)" "is not on rust-libp2p master" "$root" "$remote" "$fixenv"
root=$(fixture no-master "$later")
check fail "remote without a master branch: fail closed" "cannot fetch" "$root" "LIBP2P_REMOTE=file://$nomaster" "$fixenv"
root=$(fixture skipped "$base")
check pass "LIBP2P_SKIP_ANCESTRY=1 skips only the ancestry step" "SKIPPED" "$root" LIBP2P_SKIP_ANCESTRY=1

# Two rust-libp2p SHAs in one lockfile.
root=$(fixture two-shas "$later")
pkg libp2p-gossipsub 0.50.0 "$(src "$side")" >> "$root/Cargo.lock"
check fail "lockfile with two rust-libp2p SHAs" "2 rust-libp2p commits" "$root" "$remote" "$fixenv"

# Every libp2p* crate from that one source, once.
root=$(fixture registry "$later")
pkg libp2p-gossipsub 0.50.0 "registry+https://github.com/rust-lang/crates.io-index" >> "$root/Cargo.lock"
check fail "a libp2p* crate from crates.io" "libp2p-gossipsub 0.50.0 does not come from" "$root" "$remote" "$fixenv"
root=$(fixture fork "$later")
pkg libp2p-gossipsub 0.50.0 "git+https://github.com/someone/rust-libp2p-fork?rev=$later#$later" >> "$root/Cargo.lock"
check fail "a libp2p* crate from another git repo" "libp2p-gossipsub 0.50.0 does not come from" "$root" "$remote" "$fixenv"
root=$(fixture no-source "$later")
pkg libp2p-local 0.1.0 >> "$root/Cargo.lock"
check fail "a libp2p* crate without a source" "libp2p-local 0.1.0 does not come from" "$root" "$remote" "$fixenv"
root=$(fixture dup-name "$later")
pkg libp2p-swarm 0.47.1 "$(src "$later")" >> "$root/Cargo.lock"
check fail "a libp2p* crate in two versions" "libp2p-swarm appears 2 times" "$root" "$remote" "$fixenv"

# The lockfile is read as TOML, not line by line: cargo --locked accepts any layout of the same data.
reg="registry+https://github.com/rust-lang/crates.io-index"
root=$(fixture indented "$later")
printf '\n[[package]]\n  name = "libp2p-swarm"\n  version = "0.47.1"\n  source = "%s"\n' "$reg" >> "$root/Cargo.lock"
check fail "an indented crates.io libp2p-swarm entry" "libp2p-swarm 0.47.1 does not come from" "$root" "$remote" "$fixenv"
root=$(fixture compact "$later")
printf "\n[[ package ]]\nname='libp2p-swarm'\nversion='0.47.1'\nsource='%s'\n" "$reg" >> "$root/Cargo.lock"
check fail "a compact single-quoted crates.io libp2p-swarm entry" "libp2p-swarm appears 2 times" "$root" "$remote" "$fixenv"
root=$(fixture inline "$later")
printf 'version = 4\npackage = [\n  { name = "libp2p", version = "0.57.1", source = "%s" },\n  { name = "libp2p-swarm", version = "0.47.1", source = "%s" },\n]\n' \
  "$(src "$later")" "$reg" > "$root/Cargo.lock"
check fail "packages as an inline array" "libp2p-swarm 0.47.1 does not come from" "$root" "$remote" "$fixenv"
root=$(fixture indented-source "$later")
printf '\n[[package]]\nname = "rw-stream-sink"\nversion = "0.5.0"\n    source = "%s"\n' "$(src "$side")" >> "$root/Cargo.lock"
check fail "an indented second rust-libp2p source" "2 rust-libp2p commits" "$root" "$remote" "$fixenv"
root=$(fixture bad-toml "$later")
printf '\n[[package]\nname = "libp2p-swarm"\n' >> "$root/Cargo.lock"
check fail "a lockfile that is not TOML" "Cargo.lock: not valid TOML" "$root" "$remote" "$fixenv"

# The rust-libp2p source itself: https, ?rev= with the full 40-hex SHA, resolved to that SHA.
root=$(fixture short-rev "$later")
pkg libp2p-gossipsub 0.50.0 "git+$url?rev=${later:0:7}#$later" >> "$root/Cargo.lock"
check fail "short rev in the requested rev" "not pinned by a full rev" "$root" "$remote" "$fixenv"
root=$(fixture branch "$later")
pkg libp2p-gossipsub 0.50.0 "git+$url?branch=master#$later" >> "$root/Cargo.lock"
check fail "branch instead of rev" "not pinned by a full rev" "$root" "$remote" "$fixenv"
root=$(fixture mismatch "$later")
pkg libp2p-gossipsub 0.50.0 "git+$url?rev=$later#$fix" >> "$root/Cargo.lock"
check fail "requested rev differs from the resolved SHA" "not pinned by a full rev" "$root" "$remote" "$fixenv"
root=$(fixture ssh "$later")
pkg libp2p-gossipsub 0.50.0 "git+ssh://git@github.com/libp2p/rust-libp2p?rev=$later#$later" >> "$root/Cargo.lock"
check fail "rust-libp2p over another URL" "not pinned by a full rev" "$root" "$remote" "$fixenv"

# Missing pieces.
root=$(fixture none "$later")
grep -v rust-libp2p "$root/Cargo.lock" | grep -v '^name = "libp2p' > "$root/lock.tmp" && mv "$root/lock.tmp" "$root/Cargo.lock"
check fail "no rust-libp2p source at all" "no rust-libp2p git source" "$root" "$remote" "$fixenv"
root=$(fixture nolock "$later")
rm "$root/Cargo.lock"
check fail "no Cargo.lock" "Cargo.lock must be committed" "$root" "$remote" "$fixenv"

# Manifests: every rust-libp2p git dep names the locked SHA as its full rev.
root=$(fixture manifest-rev "$later")
printf 'libp2p-mplex = { git = "%s", rev = "%s" }\n' "$url" "$fix" >> "$root/Cargo.toml"
check fail "a manifest rev other than the locked SHA" "Cargo.toml: rust-libp2p not pinned to $later" "$root" "$remote" "$fixenv"
root=$(fixture manifest-branch "$later")
mkdir -p "$root/p2p"
printf '[dependencies]\nlibp2p = { git = "%s", branch = "master" }\n' "$url" > "$root/p2p/Cargo.toml"
check fail "a member manifest with a branch dep" "Cargo.toml: rust-libp2p not pinned to $later" "$root" "$remote" "$fixenv"

# deny.toml: no libp2p* crate may be excused from multiple-versions.
root=$(fixture deny-other "$later")
printf '[bans]\nmultiple-versions = "deny"\nskip = [\n  { crate = "syn@2.0.119", reason = "x" },\n]\ndeny = [{ crate = "libp2p-mplex", reason = "y" }]\n' > "$root/deny.toml"
check pass "deny.toml skips only non-libp2p crates" "libp2p revs OK" "$root" "$remote" "$fixenv"
root=$(fixture deny-skip "$later")
printf '[bans]\nskip = [\n  { crate = "syn@2.0.119", reason = "x" },\n  { crate = "libp2p-swarm@0.47.1", reason = "x" },\n]\n' > "$root/deny.toml"
check fail "deny.toml skip entry for a libp2p* crate" "deny.toml: libp2p* crate in [bans] skip" "$root" "$remote" "$fixenv"
root=$(fixture deny-skip-tree "$later")
printf '[bans]\nskip-tree = [{ crate = "libp2p", reason = "x" }]\n' > "$root/deny.toml"
check fail "deny.toml skip-tree entry for libp2p" "deny.toml: libp2p* crate in [bans] skip" "$root" "$remote" "$fixenv"

# Every form cargo-deny accepts for a skip or skip-tree entry, in any TOML layout.
deny_case() {
  local name=$1 desc=$2 body=$3
  root=$(fixture "deny-$name" "$later")
  printf '%s\n' "$body" > "$root/deny.toml"
  check fail "deny.toml: $desc" "deny.toml: libp2p* crate in [bans] skip" "$root" "$remote" "$fixenv"
}
deny_case single "single-quoted crate" "[bans]
skip = [{ crate = 'libp2p-swarm@0.47.1', reason = 'x' }]"
deny_case name-version "a { name, version } table" '[bans]
skip = [{ name = "libp2p-core", version = "=0.43.0" }]'
deny_case string-version "a plain name@version string" '[bans]
skip = ["libp2p-core@0.43.0"]'
deny_case string-name "a plain name string in skip-tree" '[bans]
skip-tree = ["libp2p-core"]'
deny_case dotted "a dotted bans.skip key" 'bans.skip = [{ crate = "libp2p-swarm@0.47.1", reason = "x" }]'
deny_case array-table "an [[bans.skip]] array of tables" '[[bans.skip-tree]]
crate = "libp2p"
reason = "x"'
deny_case multiline "an entry split over lines" '[bans]
skip = [
  { crate = "syn@2.0.119", reason = "x" }, { reason = "y",
    crate = "libp2p-swarm@0.47.1" },
]'
deny_case quoted-key "a quoted \"crate\" key" '[bans]
skip = [{ "crate" = "libp2p-swarm@0.47.1", reason = "x" }]'
root=$(fixture deny-unknown "$later")
printf '[bans]\nskip = [42]\n' > "$root/deny.toml"
check fail "deny.toml: an entry form it does not know fails closed" "deny.toml: [bans] skip entry not understood" "$root" "$remote" "$fixenv"
root=$(fixture deny-bad "$later")
printf '[bans\nskip = []\n' > "$root/deny.toml"
check fail "deny.toml that is not TOML" "deny.toml: not valid TOML" "$root" "$remote" "$fixenv"

# The throwaway fetch repo starts no background maintenance: a detached `git maintenance run --auto`
# (its commit-graph write) can recreate files in it while the EXIT trap removes it.
root=$(fixture no-maintenance "$later")
check pass "the ancestry fetch runs without auto maintenance" "libp2p revs OK" "$root" "$remote" "$fixenv" \
  "GIT_TRACE2=$tmp/no-maintenance.trace2"
if grep -qE 'child_start.*(maintenance run|gc --auto)' "$tmp/no-maintenance.trace2"; then
  failed=$((failed + 1)); echo "FAIL - the ancestry fetch runs without auto maintenance (trace2 shows it started)"
  grep -E 'child_start.*(maintenance run|gc --auto)' "$tmp/no-maintenance.trace2" | sed 's/^/       /'
else
  passed=$((passed + 1)); echo "ok   - trace2 shows no maintenance or gc started"
fi

# Removing the throwaway repo is best effort: a directory that rm -rf cannot empty leaves the
# verdict, pass or fail, as the check found it. A stand-in git plants one before each merge-base.
if [[ $(id -u) == 0 ]]; then
  echo "skip - cleanup failure cases (root can remove a read-only directory)"
else
  real_git=$(command -v git)
  mkdir -p "$tmp/held-bin"
  cat > "$tmp/held-bin/git" <<STUB
#!/bin/sh
if [ "\$1" = -C ] && [ "\$3" = merge-base ] && [ ! -d "\$2/held" ]; then
  mkdir "\$2/held" && : > "\$2/held/file" && chmod 0500 "\$2/held" && printf '%s\n' "\$2" >> "$tmp/held.list"
fi
exec "$real_git" "\$@"
STUB
  chmod +x "$tmp/held-bin/git"
  held_path="PATH=$tmp/held-bin:$PATH"
  root=$(fixture held-pass "$later")
  check pass "cleanup failure keeps a pass a pass" "libp2p revs OK" "$root" "$remote" "$fixenv" "$held_path"
  root=$(fixture held-fail "$side")
  check fail "cleanup failure keeps a fail a fail" "does not contain" "$root" "$remote" "$fixenv" "$held_path"
  if [[ $(wc -l < "$tmp/held.list" 2>/dev/null || echo 0) -ne 2 ]]; then
    failed=$((failed + 1)); echo "FAIL - the stand-in git planted a held directory in both runs"
  else
    passed=$((passed + 1)); echo "ok   - the stand-in git planted a held directory in both runs"
  fi
  while IFS= read -r d; do chmod -R u+w "$d" && rm -rf "$d"; done < "$tmp/held.list"
fi

# The real lockfile (ancestry stubbed: no network in this test).
check pass "real Cargo.lock" "libp2p revs OK" "$repo" LIBP2P_SKIP_ANCESTRY=1

echo "# $passed passed, $failed failed"
((failed == 0))
